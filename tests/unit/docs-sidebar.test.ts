import { describe, expect, it } from 'vitest';
import { buildSidebar, groupHolds, readingOrder, type NavNode, type SidebarEntry } from '@/lib/docs/sidebar';

const page = (slug: string, title: string, order?: number) => ({ slug, title, order });

const PAGES = [
  page('', 'NightDocs'),
  page('overview/terminology', 'Terminology'),
  page('overview/choosing-a-product', 'Choosing a product'),
  page('dusk', 'Dusk'),
  page('dusk/installation', 'Installation'),
  page('dusk/architecture', 'Architecture'),
  page('dusk/dpm', 'DPM'),
  page('dusk/dpm/publishing', 'Publishing'),
  page('dusk/dpm/registry', 'DPM Registry'),
  page('dusk/dpm/registry/setup', 'Setup'),
  page('dusk/reference', 'Reference'),
  page('dusk/reference/networking', 'Networking'),
  page('services/nebula', 'Nebula', 1),
  page('services/nebula/deployment', 'Deployment and operation', 2),
  page('services/nebula/archive', 'Archive'),
  page('reference', 'Reference'),
  page('reference/nova-api', 'Nova API'),
];

const labels = (nodes: readonly NavNode[]): unknown[] => nodes.map((node) => (node.kind === 'link' ? node.label : { [node.label]: labels(node.items) }));

describe('buildSidebar', () => {
  it('lists an autogenerated folder alphabetically', () => {
    const [group] = buildSidebar([{ label: 'Overview', items: [{ autogenerate: { directory: 'overview' } }] }], PAGES);
    expect(labels([group])).toEqual([{ Overview: ['Choosing a product', 'Terminology'] }]);
  });

  it('puts the folder index first and turns subfolders into groups named by their index', () => {
    const [dusk] = buildSidebar([{ label: 'Dusk', items: [{ autogenerate: { directory: 'dusk' } }] }], PAGES);
    expect(labels([dusk])).toEqual([
      {
        Dusk: [
          'Overview',
          'Architecture',
          { DPM: ['Overview', 'Publishing', { 'DPM Registry': ['Overview', 'Setup'] }] },
          'Installation',
          { Reference: ['Overview', 'Networking'] },
        ],
      },
    ]);
  });

  it('sorts by sidebar order before the slug', () => {
    const [nebula] = buildSidebar([{ label: 'Nebula', items: [{ autogenerate: { directory: 'services/nebula' } }] }], PAGES);
    expect(labels([nebula])).toEqual([{ Nebula: ['Overview', 'Deployment and operation', 'Archive'] }]);
  });

  it('takes explicit slugs with optional labels', () => {
    const entries: SidebarEntry[] = [{ label: 'Reference', items: [{ slug: 'reference', label: 'Overview' }, { slug: 'reference/nova-api' }] }];
    expect(labels(buildSidebar(entries, PAGES))).toEqual([{ Reference: ['Overview', 'Nova API'] }]);
  });

  it('keeps the collapsed flag on groups and nested folders', () => {
    const [group] = buildSidebar([{ label: 'Dusk', collapsed: true, items: [{ autogenerate: { directory: 'dusk', collapsed: true } }] }], PAGES);
    expect(group).toMatchObject({ kind: 'group', collapsed: true });
    const dpm = group.kind === 'group' ? group.items.find((node) => node.label === 'DPM') : undefined;
    expect(dpm).toMatchObject({ kind: 'group', collapsed: true });
  });

  it('throws on a slug that is not a published page', () => {
    expect(() => buildSidebar([{ slug: 'eclipse' }], PAGES)).toThrow(/eclipse/);
  });

  it('throws on an empty autogenerated folder', () => {
    expect(() => buildSidebar([{ autogenerate: { directory: 'nope' } }], PAGES)).toThrow(/nope/);
  });
});

describe('readingOrder', () => {
  it('walks links depth first', () => {
    const nodes = buildSidebar([{ label: 'Dusk', items: [{ autogenerate: { directory: 'dusk' } }] }], PAGES);
    expect(readingOrder(nodes)).toEqual(['dusk', 'dusk/architecture', 'dusk/dpm', 'dusk/dpm/publishing', 'dusk/dpm/registry', 'dusk/dpm/registry/setup', 'dusk/installation', 'dusk/reference', 'dusk/reference/networking']);
  });
});

describe('groupHolds', () => {
  it('finds a page anywhere under a group', () => {
    const [dusk] = buildSidebar([{ label: 'Dusk', items: [{ autogenerate: { directory: 'dusk' } }] }], PAGES);
    expect(dusk.kind === 'group' && groupHolds(dusk, 'dusk/dpm/registry/setup')).toBe(true);
    expect(dusk.kind === 'group' && groupHolds(dusk, 'reference')).toBe(false);
  });
});
